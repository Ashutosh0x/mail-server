-- ── Storage federation ────────────────────────────────────────────────────
--
-- External providers are the source of truth for their own bytes. These tables
-- hold the connection, where it is mounted, who can see the mount, and an
-- index of items — never a copy of the content, unless the user explicitly
-- imports it (which makes it a native file with its own row elsewhere).

CREATE TABLE IF NOT EXISTS storage_connections (
  id              TEXT PRIMARY KEY,
  organization_id TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  -- NULL for an organization-owned connection created by an admin.
  owner_user_id   TEXT REFERENCES users(id) ON DELETE CASCADE,
  provider        TEXT NOT NULL,
  display_name    TEXT NOT NULL,
  status          TEXT NOT NULL DEFAULT 'disconnected'
                    CHECK (status IN ('active','degraded','auth_required','revoked','unreachable','disconnected')),
  status_detail   TEXT,
  -- AES-256-GCM envelope, bound to this row's id as AAD. A dump of this table
  -- is not a usable set of provider credentials.
  encrypted_credentials TEXT,
  last_sync_at    TEXT,
  created_at      TEXT NOT NULL,
  updated_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS storage_connections_org_idx ON storage_connections(organization_id);
CREATE INDEX IF NOT EXISTS storage_connections_owner_idx ON storage_connections(owner_user_id);

CREATE TABLE IF NOT EXISTS storage_mounts (
  id              TEXT PRIMARY KEY,
  connection_id   TEXT NOT NULL REFERENCES storage_connections(id) ON DELETE CASCADE,
  organization_id TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  root_path       TEXT NOT NULL DEFAULT '/',
  -- 'private' is the default on purpose: connecting a personal account must
  -- not expose it to the whole organization.
  visibility      TEXT NOT NULL DEFAULT 'private'
                    CHECK (visibility IN ('private','organization','group','users')),
  granted_group_ids TEXT NOT NULL DEFAULT '[]',
  granted_user_ids  TEXT NOT NULL DEFAULT '[]',
  max_role        TEXT NOT NULL DEFAULT 'viewer'
                    CHECK (max_role IN ('viewer','commenter','contributor','content_manager','manager')),
  indexing        TEXT NOT NULL DEFAULT 'metadata'
                    CHECK (indexing IN ('disabled','metadata','metadata_and_text','full_content')),
  created_at      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS storage_mounts_connection_idx ON storage_mounts(connection_id);
CREATE INDEX IF NOT EXISTS storage_mounts_org_idx ON storage_mounts(organization_id);

CREATE TABLE IF NOT EXISTS storage_items (
  id              TEXT PRIMARY KEY,
  connection_id   TEXT NOT NULL REFERENCES storage_connections(id) ON DELETE CASCADE,
  -- The provider's id, unique only WITHIN a connection. Never a primary key:
  -- two providers will collide.
  external_id     TEXT NOT NULL,
  parent_external_id TEXT,
  name            TEXT NOT NULL,
  mime_type       TEXT NOT NULL DEFAULT 'application/octet-stream',
  size_bytes      INTEGER,
  is_folder       INTEGER NOT NULL DEFAULT 0,
  modified_at     TEXT,
  web_url         TEXT,
  indexed_at      TEXT,
  created_at      TEXT NOT NULL,
  UNIQUE (connection_id, external_id)
);
CREATE INDEX IF NOT EXISTS storage_items_parent_idx ON storage_items(connection_id, parent_external_id);

CREATE TABLE IF NOT EXISTS storage_sync_states (
  connection_id   TEXT PRIMARY KEY REFERENCES storage_connections(id) ON DELETE CASCADE,
  -- Provider change cursor. Incremental sync depends on this; a full re-crawl
  -- on every request is what it exists to avoid.
  change_cursor   TEXT,
  last_sync_at    TEXT,
  last_error      TEXT,
  items_indexed   INTEGER NOT NULL DEFAULT 0,
  updated_at      TEXT NOT NULL
);
